import assert from 'node:assert/strict';
import fs from 'node:fs';
import {fileURLToPath} from 'node:url';
import path from 'node:path';
import {resolveMengjinStageLocation} from '../public/mengjin-stage-route.js';
import {sceneIndexStatus, MENGJIN_ACTS} from '../public/mengjin-story-catalog.js';
import {expectedJadeAnswers, verifyTeachingAnswers, boardStationForLocation} from '../public/mengjin-board.js';
const dirname=path.dirname(fileURLToPath(import.meta.url));
const rules=JSON.parse(fs.readFileSync(path.join(dirname,'../public/scene-activities/mengjin-teaching-boards.json'),'utf8'));
const spot={id:'mengjin-river-gate',locationId:'mengjin-jade-courtyard'};
const chapter={quests:{side:[{id:'mengjin-jade-mainline'},{id:'mengjin-diviner-mainline'}]},locations:[{id:'mengjin-jade-courtyard'},{id:'mengjin-diviner-residence'}]};
const fixture={tasks:{side:{}}};
assert.equal(resolveMengjinStageLocation(chapter,fixture,spot),'mengjin-jade-courtyard');
fixture.tasks.side['mengjin-jade-mainline']={status:'accepted',steps:{}};
assert.equal(resolveMengjinStageLocation(chapter,fixture,spot),'mengjin-jade-courtyard');
fixture.tasks.side['mengjin-jade-mainline'].status='completed';
assert.equal(resolveMengjinStageLocation(chapter,fixture,spot),'mengjin-jade-courtyard');
fixture.tasks.side['mengjin-jade-mainline'].status='submitted';
assert.equal(resolveMengjinStageLocation(chapter,fixture,spot),'mengjin-diviner-residence');
assert.equal(sceneIndexStatus(fixture,MENGJIN_ACTS[4]),'current');
assert.equal(sceneIndexStatus(fixture,MENGJIN_ACTS[6]),'locked');
assert.equal(MENGJIN_ACTS.length,34);
assert.equal(boardStationForLocation('mengjin-diviner-residence'),302);
assert.equal(boardStationForLocation('mengjin-jade-courtyard'),226);
assert.deepEqual(expectedJadeAnswers(rules.jade),{bits:6,decodedOffering:'豆',encoded:'000101'});
assert(verifyTeachingAnswers(rules.jade.id,{bits:6,decodedOffering:'豆',encoded:'000101'},rules));
assert(!verifyTeachingAnswers(rules.jade.id,{bits:6,decodedOffering:'豆',encoded:'000100'},rules));
assert(verifyTeachingAnswers(rules.diviner.id,{seen:['00','01','11','10']},rules));
assert(!verifyTeachingAnswers(rules.diviner.id,{seen:['00','01']},rules));
console.log('孟津正式主线：阶段路由 / 扩展目录 / 教学题板 / 物理站位测试通过');
